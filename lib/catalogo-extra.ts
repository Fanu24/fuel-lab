import { kcalDa } from "./types";
import type { Extra } from "./catalogo";

/*
 * Gli alimenti della box, separati da catalogo.ts solo per tenerlo leggibile.
 *
 * L'ORDINE DI QUESTO ARRAY E' UN CONTRATTO. condivisione.ts codifica gli extra
 * come bit di una maschera per posizione e firma il catalogo con un'impronta
 * calcolata su questi id in fila: spostare una riga invalida tutti i link gia'
 * condivisi. Si aggiunge in fondo, non si riordina.
 *
 * Il tipo Extra resta in catalogo.ts: l'import e' solo di tipo, sparisce alla
 * compilazione e non crea il ciclo che un import di valore creerebbe.
 */

function extra(
  parziale: Omit<Extra, "kcal"> & { proteine: number; carboidrati: number; grassi: number },
): Extra {
  return { ...parziale, kcal: kcalDa(parziale.proteine, parziale.carboidrati, parziale.grassi) };
}

